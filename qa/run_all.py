#!/usr/bin/env python3
"""Run the complete Orion QA pipeline and write qa/reports/QA-SUMMARY.md.

    python3 qa/run_all.py            # everything
    python3 qa/run_all.py shaping    # one suite
Set ORION_REFERENCE=/path/to/Reference to include reference-family measurements in the accessibility suite."""
import os, sys, json, subprocess, time, glob
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
SUITES = ['integrity', 'interpolation', 'shaping', 'unicode', 'rendering', 'accessibility', 'performance']


def fontbakery():
    out = os.path.join(HERE, 'fontbakery'); os.makedirs(out, exist_ok=True)
    targets = {'Orion-VF': [os.path.join(ROOT, 'fonts', 'variable', 'Orion-VF.ttf')],
               'Orion-static-ttf': sorted(glob.glob(os.path.join(ROOT, 'fonts', 'static', 'Orion', '*.ttf'))),
               'OrionDisplay-static-ttf': sorted(glob.glob(os.path.join(ROOT, 'fonts', 'static', 'OrionDisplay', '*.ttf'))),
               'OrionCondensed-static-ttf': sorted(glob.glob(os.path.join(ROOT, 'fonts', 'static', 'OrionCondensed', '*.ttf'))),
               'Orion-static-otf': sorted(glob.glob(os.path.join(ROOT, 'fonts', 'static-otf', '*.otf')))}
    res = {}
    for name, files in targets.items():
        if not files:
            continue
        js = os.path.join(out, name + '.universal.json')
        subprocess.run(['fontbakery', 'check-universal', '-q', '--no-progress', '--no-colors', '-l', 'WARN', '--json', js] + files,
                       capture_output=True, text=True)
        d = json.load(open(js))
        notes = {}
        for sec in d['sections']:
            for c in sec['checks']:
                if c['result'] in ('FAIL', 'ERROR', 'WARN'):
                    cid = str(c['key'][1]).replace('<FontBakeryCheck:', '').rstrip('>')
                    codes = sorted({(l.get('message') or {}).get('code', '') for l in c['logs'] if isinstance(l.get('message'), dict) and l.get('status') in ('FAIL', 'ERROR', 'WARN')})
                    notes.setdefault(c['result'], {}).setdefault(cid, set()).update(codes)
        res[name] = dict(fonts=len(files), result=d['result'], notes={k: {c: sorted(v) for c, v in vv.items()} for k, vv in notes.items()})
        print('fontbakery %-26s %s' % (name, d['result']))
    json.dump(res, open(os.path.join(HERE, 'reports', 'fontbakery.json'), 'w'), indent=1)
    return res


def main():
    which = sys.argv[1:] or SUITES + ['fontbakery']
    os.makedirs(os.path.join(HERE, 'reports'), exist_ok=True)
    t0 = time.time()
    for s in SUITES:
        if s in which:
            r = subprocess.run([sys.executable, os.path.join(HERE, 'qa_%s.py' % s)], cwd=HERE, capture_output=True, text=True)
            sys.stdout.write(r.stdout[-2500:])
            if r.returncode != 0:
                sys.stdout.write(r.stderr[-2500:])
    fb = fontbakery() if 'fontbakery' in which else (json.load(open(os.path.join(HERE, 'reports', 'fontbakery.json'))) if os.path.exists(os.path.join(HERE, 'reports', 'fontbakery.json')) else {})
    # ---- summary
    L = ['# Orion QA summary', '', 'Generated by `qa/run_all.py`. Every figure below is produced by the scripts in `qa/` against the binaries in `fonts/`.', '',
         '| Suite | PASS | WARN | FAIL | SKIP |', '|---|---:|---:|---:|---:|']
    tot = dict(PASS=0, WARN=0, FAIL=0, SKIP=0); open_items = []
    for s in SUITES:
        p = os.path.join(HERE, 'reports', s + '.json')
        if not os.path.exists(p):
            continue
        d = json.load(open(p)); c = d['summary']
        L.append('| %s | %d | %d | %d | %d |' % (s, c.get('PASS', 0), c.get('WARN', 0), c.get('FAIL', 0), c.get('SKIP', 0)))
        for k in tot:
            tot[k] += c.get(k, 0)
        for r in d['results']:
            if r['status'] != 'PASS':
                open_items.append((s, r['status'], r['check'], str(r['detail'])[:260]))
    L.append('| **total** | **%d** | **%d** | **%d** | **%d** |' % (tot['PASS'], tot['WARN'], tot['FAIL'], tot['SKIP']))
    L += ['', '## FontBakery (universal profile)', '', '| Target | Fonts | PASS | WARN | FAIL | ERROR | SKIP |', '|---|---:|---:|---:|---:|---:|---:|']
    for name, r in fb.items():
        c = r['result']
        L.append('| %s | %d | %d | %d | %d | %d | %d |' % (name, r['fonts'], c.get('PASS', 0), c.get('WARN', 0), c.get('FAIL', 0), c.get('ERROR', 0), c.get('SKIP', 0)))
    L += ['', '### FontBakery findings', '']
    for name, r in fb.items():
        for lvl in ('FAIL', 'ERROR', 'WARN'):
            for cid, codes in r['notes'].get(lvl, {}).items():
                L.append('- **%s** `%s` — %s (%s)' % (lvl, cid, ', '.join(c for c in codes if c) or 'see JSON', name))
    L += ['', '## Open items from the Orion suites (WARN / FAIL / SKIP)', '']
    if not open_items:
        L.append('None.')
    for s, st, chk, det in open_items:
        L.append('- **%s** [%s] %s%s' % (st, s, chk, (' — `%s`' % det.replace('|', '/')) if det else ''))
    L += ['', '_Run time: %d s._' % (time.time() - t0), '']
    open(os.path.join(HERE, 'reports', 'QA-SUMMARY.md'), 'w').write('\n'.join(L))
    print('TOTAL', tot)


if __name__ == '__main__':
    main()
